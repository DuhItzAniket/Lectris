"""Report a calibrated pack (LX-CAL-*): thresholds, calibration, the loss curve, the weights.

For each profile, the estimated mean loss on the calibration pages at each threshold of the
grid, the Hoeffding-Bentkus p-value there, and the smallest budget the calibration pages could
certify at all (the risk of zero observed loss: ``1 - delta ** (1 / n)``). Aggregates only.

    uv run python scripts/report_calibration.py --id LX-CAL-001 --pack P --cal CAL --out DIR
"""

import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from lectris.eval.calibrate import loss_at, page_candidates, page_losses
from lectris.eval.experiment import load_pairs
from lectris.models import pack
from lectris.models.risk import grid, hoeffding_bentkus

SHOWN = (1.0, 0.99, 0.98, 0.95, 0.9, 0.8, 0.7, 0.6, 0.5, 0.4, 0.3, 0.2, 0.1, 0.0)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--id", required=True)
    parser.add_argument("--pack", type=Path, required=True)
    parser.add_argument("--cal", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    arguments = parser.parse_args(argv)
    model = pack.load(arguments.pack)
    if model.acceptance is None or model.risk is None or model.calibration is None:
        sys.stderr.write("the pack is not calibrated\n")
        return 1
    cal = load_pairs(arguments.cal)
    profiles: dict[str, Any] = {}
    for name, budget in sorted(model.risk.items()):
        pages = page_candidates(cal, model, name)
        scored = page_losses(pages, model.acceptance)
        curve = []
        for threshold in grid(100):
            losses = loss_at(threshold, scored, pages)
            mean = sum(losses) / len(losses)
            accepted = sum(1 for items in scored for p, _ in items if p >= threshold)
            net = sum(
                item.effect
                for page in pages
                for item in page.candidates
                if model.acceptance.probability(item.candidate) >= threshold
            )
            curve.append(
                {
                    "threshold": threshold,
                    "mean_loss": mean,
                    "accepted": accepted,
                    "net_effect": net,
                    "p_value": hoeffding_bentkus(mean, len(losses), budget.alpha),
                }
            )
        profiles[name] = {
            "alpha": budget.alpha,
            "delta": budget.delta,
            "threshold": budget.threshold,
            "permissive": budget.permissive,
            "pages": budget.pages,
            "smallest_certifiable_alpha": 1 - budget.delta ** (1 / budget.pages),
            "candidates": sum(len(items) for items in scored),
            "curve": curve,
        }
    weights = sorted(
        zip(model.acceptance.names, model.acceptance.weights, strict=True),
        key=lambda item: -abs(item[1]),
    )
    result = {
        "id": arguments.id,
        "calibration": dict(model.calibration),
        "profiles": profiles,
        "weights": [{"feature": n, "weight": w} for n, w in weights],
        "bias": model.acceptance.bias,
    }
    arguments.out.mkdir(parents=True, exist_ok=True)
    (arguments.out / "report.json").write_text(
        json.dumps(result, indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    (arguments.out / "report.md").write_text(markdown(result), encoding="utf-8", newline="\n")
    sys.stdout.write(markdown(result))
    return 0


def markdown(result: dict[str, Any]) -> str:
    c = result["calibration"]
    rows = [
        f"# {result['id']}",
        "",
        "The acceptance model fitted on the fit split's candidates, the thresholds chosen on the "
        "cal split by Learn-then-Test. Generated by `scripts/report_calibration.py`; aggregates "
        "only.",
        "",
        f"- Training: {c['fit_pages']} fit pages, {c['fit_candidates']} candidates, "
        f"{c['fit_fixes']} of them fixes; L2 {c['l2']}",
        f"- Calibration (standard profile, {c['cal_pages']} cal pages, "
        f"{c.get('cal_candidates', 0)} candidates, {c.get('cal_fixes', 0)} fixes): ECE "
        f"{c.get('ece', float('nan')):.4f}, Brier {c.get('brier', float('nan')):.4f}",
        "",
        "| Profile | alpha | delta | Pages | Smallest certifiable alpha "
        "| Most permissive certified | Threshold used |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, p in result["profiles"].items():
        rows.append(
            f"| {name} | {p['alpha']} | {p['delta']} | {p['pages']} | "
            f"{p['smallest_certifiable_alpha']:.5f} | {p['permissive']} | {p['threshold']} |"
        )
    rows += [
        "",
        "The smallest certifiable alpha is the risk that zero observed loss on that many pages can "
        "rule out with confidence 1 - delta: a budget below it cannot be met by any threshold.",
        "",
    ]
    for name, p in result["profiles"].items():
        rows += [
            f"## Estimated loss on cal: {name}",
            "",
            "| Threshold | Accepted candidates | Net effect (characters) | Mean page loss | "
            "Hoeffding-Bentkus p-value |",
            "|---|---|---|---|---|",
        ]
        rows.extend(
            f"| {point['threshold']} | {point['accepted']} | {point['net_effect']:+d} | "
            f"{point['mean_loss']:.6f} | "
            f"{point['p_value']:.4f} |"
            for point in p["curve"]
            if point["threshold"] in SHOWN
        )
        rows.append("")
    rows += [
        "## Reliability (standard, cal)",
        "",
        "| Mean probability | Frequency of fixes | Candidates |",
        "|---|---|---|",
    ]
    rows.extend(f"| {m:.3f} | {f:.3f} | {n} |" for m, f, n in c.get("reliability", []))
    rows += [
        "",
        "## Weights (standardised features, largest first)",
        "",
        "| Feature | Weight |",
        "|---|---|",
    ]
    rows.extend(f"| `{w['feature']}` | {w['weight']:+.3f} |" for w in result["weights"])
    rows += ["", f"Bias {result['bias']:+.3f}.", ""]
    return "\n".join(rows)


if __name__ == "__main__":
    raise SystemExit(main())
