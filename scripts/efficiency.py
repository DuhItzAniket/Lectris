"""H6: what correction costs on a CPU, next to recognition (protocol §3.6).

For every page of a pairs manifest: LECTRIS's time to read the engine's output and clean it with a
calibrated pack under the risk policy (the best of ``--repeats`` runs, after one warm-up run),
and the engine's own time for that page, read from its log (GLYPHARIS writes
``<image>: N lines in S s`` per page). Reports the medians, the 95th percentiles and the median
of the per-page ratio. One process, this machine; times differ between machines, the ratio less.
Aggregates only.

    uv run python scripts/efficiency.py --id LX-EFF-001 --pack P --pairs DEV --engine-log LOG \\
        --out reports/LX-EFF-001
"""

import argparse
import json
import platform
import re
import statistics
import sys
import time
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from lectris import clean, io
from lectris.eval.experiment import load_pairs
from lectris.models import pack

_LINE = re.compile(r"([^\\/]+)\.(?:jpg|jpeg|png|tif|tiff): \d+ lines in ([0-9.]+) s")


def engine_seconds(log: Path) -> dict[str, float]:
    """Each image's seconds in the engine's log, by image id (its file name without suffix)."""
    found = {}
    for line in log.read_text(encoding="utf-8", errors="replace").splitlines():
        match = _LINE.search(line)
        if match:
            found[match.group(1)] = float(match.group(2))
    return found


def percentile(values: Sequence[float], share: float) -> float:
    ordered = sorted(values)
    return ordered[min(len(ordered) - 1, int(share * len(ordered)))]


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--id", required=True)
    parser.add_argument("--pack", type=Path, required=True)
    parser.add_argument("--pairs", type=Path, required=True)
    parser.add_argument("--engine-log", type=Path, required=True)
    parser.add_argument("--profile", default="standard")
    parser.add_argument("--repeats", type=int, default=3)
    parser.add_argument("--out", type=Path, required=True)
    arguments = parser.parse_args(argv)

    model = pack.load(arguments.pack)
    policy = model.policy(arguments.profile)
    engine = engine_seconds(arguments.engine_log)
    ours, theirs, ratios = [], [], []
    for pair in load_pairs(arguments.pairs):
        if pair.page not in engine:
            continue

        def run(path: Path = pair.engine) -> None:
            clean(io.read(path), profile=arguments.profile, policy=policy, pack=model)

        run()  # warm-up
        best = min(_timed(run) for _ in range(arguments.repeats))
        ours.append(best)
        theirs.append(engine[pair.page])
        ratios.append(best / engine[pair.page])
    result: dict[str, Any] = {
        "id": arguments.id,
        "pages": len(ours),
        "profile": arguments.profile,
        "machine": {"python": platform.python_version(), "system": platform.system()},
        "lectris_seconds": {
            "median": statistics.median(ours),
            "p95": percentile(ours, 0.95),
            "mean": statistics.fmean(ours),
        },
        "engine_seconds": {
            "median": statistics.median(theirs),
            "p95": percentile(theirs, 0.95),
            "mean": statistics.fmean(theirs),
        },
        "ratio_median": statistics.median(ratios),
        "ratio_p95": percentile(ratios, 0.95),
        "pack_bytes": arguments.pack.stat().st_size,
    }
    arguments.out.mkdir(parents=True, exist_ok=True)
    (arguments.out / "report.json").write_text(
        json.dumps(result, indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    (arguments.out / "report.md").write_text(markdown(result), encoding="utf-8", newline="\n")
    sys.stdout.write(markdown(result))
    return 0


def _timed(run: Any) -> float:
    start = time.perf_counter()
    run()
    return time.perf_counter() - start


def markdown(result: dict[str, Any]) -> str:
    ours, theirs = result["lectris_seconds"], result["engine_seconds"]
    return "\n".join(
        [
            f"# {result['id']}",
            "",
            f"LECTRIS ({result['profile']} profile, a calibrated pack, the risk policy) against "
            "the "
            f"engine's own time, per page, on {result['pages']} pages; one process, Python "
            f"{result['machine']['python']} on {result['machine']['system']}. Generated by "
            "`scripts/efficiency.py`; aggregates only.",
            "",
            "| | Median | 95th percentile | Mean |",
            "|---|---|---|---|",
            f"| LECTRIS, seconds per page | {ours['median']:.4f} | {ours['p95']:.4f} | "
            f"{ours['mean']:.4f} |",
            f"| Engine (GLYPHARIS, from its log), seconds per page | {theirs['median']:.3f} | "
            f"{theirs['p95']:.3f} | {theirs['mean']:.3f} |",
            f"| LECTRIS / engine, per page | {result['ratio_median']:.4f} | "
            f"{result['ratio_p95']:.4f} | — |",
            "",
            f"Pack: {result['pack_bytes']:,} bytes.",
            "",
        ]
    )


if __name__ == "__main__":
    raise SystemExit(main())
